// helpText — единственная справка CLI: она же показывается при ошибке разбора.
const helpText = `atrice — управление изолированными окружениями agent-docker.

Использование:
  atrice                       список гостей, выбор стрелками (нужен терминал)
  atrice menu                  то же самое: список с буквами-действиями
  atrice cmd                   строка команд со слешем (нужен терминал)
  atrice <команда> [флаги] <VM>     флаги допускаются и после имени VM

Выбор ведут стрелки вверх и вниз или j и k. Enter только подтверждает
подсвеченный пункт: в списке гостей он выбирает гостя и показывает его живые
сессии, в списке сессий — подключается к подсвеченной сессии. Сам по себе
Enter не запускает ни гостя, ни Claude и не открывает оболочку; когда живых
сессий нет, подтверждать нечего. Обычная консоль и запуск агента остались
отдельными пунктами: c и a. Из консоли, сессии и агента возвращает Ctrl+]:
список открывается сразу, и выбранный гость остаётся под курсором. Выход из
списка — q или Ctrl+D.

Клавиши работают и в русской раскладке: нажимается та же клавиша, то есть
с — консоль, ф — Claude, г — запустить, ы — остановить, п — git, д — логи,
з — профиль, в — удалить, т — создать, к — обновить, й — выход.

В строке команд atrice cmd команды начинаются со слеша: /go vm-01,
/logs vm-02 --tail 20. Tab дополняет команду и имя гостя, стрелки вверх и вниз
листают историю, а одно имя гостя без слеша открывает его сессию.
Выход — /quit или Ctrl+D.

Окружения:
  ls                           список гостей: состояние, ресурсы, прокси, Git
                               и живые сессии по данным канала
  go <VM>                      вернуться в гостя: к живым сессиям из канала
                               через консоль, в остановленного или свободного —
                               запуском Claude
  status <VM>                  подробное состояние одного гостя
  new <VM>                     создать и подготовить гостя
    --cpu N --ram N --disk N     бюджет при первом создании
    --repo R --provider P        назначить Git-шлюз сразу при создании
    --url U --write BRANCH
    --sni-log                    включить журнал SNI на шлюзе
  setup <VM>                   повторная подготовка после обновления образа
  up [VM]                      запустить гостя, без имени — все настроенные
  stop <VM>                    штатно выключить гостя и остановить шлюз
  rm <VM>                      удалить гостя, спросив подтверждение
    --keep-disk                  сохранить диск (по умолчанию)
    --delete-disk                удалить диск вместе с проектами
    --yes                        не спрашивать подтверждение

Работа агента:
  console <VM> [--project P]   оболочка гостя
  claude <VM> [--project P] [--resume ID]
  auth <VM>                    вход Claude Code внутри гостя
  logout <VM>                  выход Claude Code

Шлюзы:
  proxy <VM>                   задать upstream-прокси гостя
  git <VM> --repo owner/name [--write BRANCH]
  git <VM> --provider gitlab --url https://gitlab.example.com --repo group/project
      [--read-branch ALIAS=BRANCH]  добавить ветку чтения с очищенной историей
  git audit <VM>               проверить, какие данные доступны в зеркале
  git host-sync <VM>           обновить зеркало только для чтения с хоста
  git host-writer <VM>         запустить публикацию Git на хосте
  git host-activate <VM>       подключить зеркало, перезапустив только шлюз
  git host-disable <VM>        отключить зеркало хоста
  git status <VM>              показать назначение шлюза без токена

Диагностика:
  logs <VM> [--service vm|proxy] [--tail N|all] [--follow]
  profile <VM>                 идентификаторы запущенного гостя
  sessions <VM>                живые сессии tmux гостя, если образ их умеет
                               подключение к выбранной сессии — Enter в списке

Общие флаги:
  --root PATH                  каталог agent-docker: явный путь, иначе
                               AGENT_DOCKER_ROOT, иначе поиск вверх от
                               каталога бинарника и текущего каталога,
                               иначе привязка из ~/.config/agent-docker/root

Установка в каталог пользователя, без root: bash cli/install.sh. Привязать
каталог проекта для запуска из любого места: bash cli/install.sh --bind.
Имя бинарника ни на что не влияет: ранее собранный agd работает по-прежнему.

Токены и пароли вводятся в запросе и остаются на хосте: CLI их не печатает,
не принимает в аргументах и не сохраняет в истории оболочки.
`
