package main

import (
	"unicode"
	"unicode/utf8"
)

// Клавиши списка читаются рунами, а не байтами. Байта мало: русская буква в
// UTF-8 занимает два байта, и первый у всех букв один и тот же — 0xD0 или
// 0xD1. Разбор по первому байту сводил всю русскую раскладку к двум
// значениям, и ни одно действие с неё не вызывалось.
const (
	// Enter приходит и как CR, и как LF: CR даёт терминал в неформатированном
	// режиме, LF — вставка, сценарий и часть удалённых клиентов. Разбор
	// приводит оба к keyEnter, иначе подтверждение пункта меню зависело бы от
	// того, чем именно его нажали.
	keyEnter  rune = 13
	keyLine   rune = 10
	keyEscape rune = 27
	// keyDetach — Ctrl+], тот же выход, что и из консоли гостя. Экран сессий
	// возвращает им в список: привычка одна на оба экрана.
	keyDetach      rune = 29
	keyInterrupt   rune = 3
	keyEndOfStream rune = 4
	// Стрелки приходят последовательностью ESC [ A. Чтобы они не совпадали с
	// буквами A и B, им отведены руны частной области.
	keyUp    rune = 0xE000 + 'A'
	keyDown  rune = 0xE000 + 'B'
	keyOther rune = 0xE000
)

// layout — русская раскладка по расположению клавиш: буква, которую печатает
// та же клавиша в ЙЦУКЕН, приводится к латинской. Это ровно то, что делает
// переключение раскладки, поэтому подсказка «c оболочка» работает и тогда,
// когда включён русский: нажимается та же клавиша.
var layout = map[rune]rune{
	'й': 'q', 'ц': 'w', 'у': 'e', 'к': 'r', 'е': 't', 'н': 'y', 'г': 'u',
	'ш': 'i', 'щ': 'o', 'з': 'p', 'х': '[', 'ъ': ']',
	'ф': 'a', 'ы': 's', 'в': 'd', 'а': 'f', 'п': 'g', 'р': 'h', 'о': 'j',
	'л': 'k', 'д': 'l', 'ж': ';', 'э': '\'',
	'я': 'z', 'ч': 'x', 'с': 'c', 'м': 'v', 'и': 'b', 'т': 'n', 'ь': 'm',
	'б': ',', 'ю': '.', 'ё': '`',
}

// foldKey приводит нажатую клавишу к латинской букве нижнего регистра:
// заглавные буквы и русская раскладка вызывают те же действия, что и
// подсказка под списком.
func foldKey(symbol rune) rune {
	lowered := unicode.ToLower(symbol)
	if latin, known := layout[lowered]; known {
		return latin
	}
	return lowered
}

// decodeKey вытаскивает из прочитанных байтов одну клавишу. Разбираются
// стрелки, а неполная или испорченная последовательность UTF-8 отдаётся
// первым байтом: на неизвестную клавишу список просто не реагирует.
func decodeKey(data []byte) rune {
	if len(data) == 0 {
		return keyOther
	}
	if rune(data[0]) == keyEscape {
		// Стрелки приходят в двух видах: CSI (ESC [ A) в обычном режиме и
		// SS3 (ESC O A) в режиме приложения, который включают tmux, screen и
		// многие терминалы. Разбирать нужно оба, иначе в одном из режимов
		// список не листался бы вовсе.
		if len(data) >= 3 && (data[1] == '[' || data[1] == 'O') {
			switch data[2] {
			case 'A':
				return keyUp
			case 'B':
				return keyDown
			}
			return keyOther
		}
		if len(data) > 1 {
			// Alt с буквой: отдельного действия у неё нет.
			return keyOther
		}
		return keyEscape
	}
	if rune(data[0]) == keyLine {
		return keyEnter
	}
	if data[0] < 0x80 {
		return foldKey(rune(data[0]))
	}
	symbol, size := utf8.DecodeRune(data)
	if symbol == utf8.RuneError && size <= 1 {
		return keyOther
	}
	return foldKey(symbol)
}
